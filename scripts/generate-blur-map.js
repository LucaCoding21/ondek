// Generates src/lib/blur-map.ts: tiny base64 blur placeholders for every
// content image under /public/images (frame sequences and tiny logos excluded).
const sharp = require('sharp');
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..', 'public');
const exts = new Set(['.jpg', '.jpeg', '.png', '.webp']);
const skipDirs = ['/images/ultra-exploded', '/images/deck-assembly', '/images/partners'];
const files = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    const rel = p.replace(root, '');
    if (e.isDirectory()) {
      if (!skipDirs.some((d) => rel.startsWith(d))) walk(p);
    } else if (exts.has(path.extname(e.name).toLowerCase()) && rel.startsWith('/images/')) {
      files.push(p);
    }
  }
})(root);

(async () => {
  const entries = [];
  for (const f of files.sort()) {
    const rel = f.replace(root, '');
    const buf = await sharp(f).rotate().resize(10, 10, { fit: 'inside' }).webp({ quality: 24, alphaQuality: 20 }).toBuffer();
    entries.push(`  "${rel}": "data:image/webp;base64,${buf.toString('base64')}",`);
  }
  const out = `// Generated by scripts/generate-blur-map.js — do not edit by hand.
// Tiny base64 previews shown while the real image loads, so photos fade in
// from a blurred wash of their own colours instead of flashing white.
export const BLUR_MAP: Record<string, string> = {
${entries.join('\n')}
};
`;
  fs.writeFileSync(path.join(__dirname, '..', 'src/lib/blur-map.ts'), out);
  console.log(`wrote ${entries.length} entries, ${Math.round(out.length / 1024)}KB`);
})();
